-- ------------------------------------------------------------
-- 背景：实施计划 `doc/plan/HelloAI 核验双域改造实施计划（2026-11-04）.md`
-- `RV-3`。核验判定输出新增 coverage[]（每条验收点的覆盖状态 + 证据方式 +
-- 证据指向），静态覆盖批评器据此判「通过是否有逐条覆盖声明」。
-- 本列把当轮判定物化下来，使 INCONCLUSIVE 的成因可回读（不靠重跑模型）。
--
-- 只增列，不改类型 / 约束 / 索引；存量行为 NULL ⇒ 旧行为（覆盖批评器对
-- 历史记录不回溯）。
-- ============================================================

ALTER TABLE review_record ADD COLUMN IF NOT EXISTS coverage JSONB;

COMMENT ON COLUMN review_record.coverage IS
    '验收点覆盖清单（RV-3）：[{criterionRef,status,method,evidenceRef,note}]；NULL = 该轮未产出覆盖清单（历史行或模型未填）';
