package com.helloai.core.agent.quality.gate;

/**
 * 质量闸门判定结论（目标架构 B4「Quality Gate 泛化」/ RM12 的统一决策语义）。
 *
 * <p>把原先散落三域的判定收敛到同一套结论词汇：既能表达<b>拦截型</b>闸门
 * （{@link #BLOCK}，可阻断/驳回）与<b>建议型</b>判定（{@link #ADVISE}，只给信号不阻断），
 * 也能表达「判定不适用」的 {@link #SKIP}。</p>
 *
 * <p><b>边界</b>：本枚举只描述「结论」，<b>不承载任何判定逻辑</b>——收口期既有判定逐字不动。</p>
 */
public enum GateOutcome {

    /** 通过：无任何需处理项。 */
    PASS,

    /** 拦截：命中硬违规 / 硬判据，调用方可据此阻断或驳回。 */
    BLOCK,

    /** 建议：产出了需关注项但不足以阻断（软违规 / 语义建议），交下游复核。 */
    ADVISE,

    /** 跳过：输入缺失或不适用，未作判定（<b>不得</b>视为通过）。 */
    SKIP
}
